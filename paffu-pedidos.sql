-- Pedidos de la tienda Paffu. Correr una vez en Supabase (SQL Editor).
-- La tienda escribe aquí solo a través de las funciones de Netlify (service role).
-- El panel (usuarios con login) puede ver y cambiar el estado.

create extension if not exists pgcrypto;

create table if not exists public.pedidos (
  id uuid primary key default gen_random_uuid(),
  num bigint generated by default as identity (start with 1001) unique,
  created_at timestamptz not null default now(),
  estado text not null default 'pendiente_pago',
  -- pendiente_pago · pago_pendiente · pago_rechazado · error_pago · esperando_transferencia
  -- pagado · pagado_revisar · preparando · despachado · entregado · cancelado
  pago text not null,            -- mercadopago | transferencia
  cliente jsonb not null,        -- {nombre, email, telefono}
  entrega jsonb not null,        -- {metodo, region, direccion, comuna}
  items jsonb not null,          -- [{id, name, t, label, q, precio, oprecio}]
  subtotal integer not null,
  envio integer not null default 0,
  total integer not null,
  mp_preference text,
  mp_payment text,
  pagado_at timestamptz,
  nota text
);

alter table public.pedidos enable row level security;

drop policy if exists "panel ve pedidos" on public.pedidos;
create policy "panel ve pedidos" on public.pedidos for select to authenticated using (true);
drop policy if exists "panel cambia pedidos" on public.pedidos;
create policy "panel cambia pedidos" on public.pedidos for update to authenticated using (true) with check (true);

-- Avisos en vivo en el panel cuando entra un pedido
do $$ begin
  alter publication supabase_realtime add table public.pedidos;
exception when duplicate_object then null; end $$;
